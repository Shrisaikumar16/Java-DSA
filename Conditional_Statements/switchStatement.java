
public class switchStatement {
    public static void main(String args[]) {
        int number = 1;
        switch(number) {
            case 1:
                System.out.println("samosa");
                break;
            case 2:
                System.out.println("burger");   
                break;
            case 3:
                System.out.println("pizza");
                break;
            default:
                System.out.println("Invalid choice");
                break;

        }
    }
}
